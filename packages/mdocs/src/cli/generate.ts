import { mkdirSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative, sep } from "node:path";

/**
 * Windows separators in a specifier build silently and split nothing.
 *
 * Across two Windows drives there is no relative path, and `relative` hands back
 * the absolute target; prefixing it with `./` would name a folder called `D:`.
 */
export function specifier(from: string, to: string): string {
  const rel = relative(from, to);
  const path = rel.split(sep).join("/");
  if (isAbsolute(rel)) return path;
  return path.startsWith(".") ? path : `./${path}`;
}

export interface GenerateUi {
  readonly ui?: string;
  readonly asks?: boolean;
}

export interface GenerateResult {
  readonly dir: string;
  readonly registry: string;
  readonly entry: string;
}

/**
 * The generated half of the registry: ids in, literal dynamic imports out.
 *
 * It has to be a file on disk with literal specifiers, and not a map assembled
 * at runtime, because that is the only form `Bun.build({ splitting: true })` can
 * see. Build a specifier from a variable and the bundler cannot follow it: the
 * build still succeeds, nothing is split, and the reader downloads every demo on
 * the site inside the first script. The failure is silent and only visible in a
 * chunk count.
 */
export function generate(
  root: string,
  demosDir: string,
  ids: readonly string[],
  scripts: readonly string[],
  { ui, asks = false }: GenerateUi = {},
): GenerateResult {
  const dir = join(root, ".mdocs");
  mkdirSync(dir, { recursive: true });

  const entries = ids
    .map((id) => `  ${JSON.stringify(id)}: () => import("${specifier(dir, join(demosDir, id))}"),`)
    .join("\n");

  const registry = join(dir, "registry.ts");
  writeFileSync(
    registry,
    `// Generated by \`mdocs build\`. Do not edit.\nimport type { DemoRegistry } from "@standarx/mdocs/react/registry";\n\nexport const DEMOS: DemoRegistry = {\n${entries}\n};\n`,
    "utf8",
  );

  // The deep specifiers are the point, and they are not a style preference: the
  // kit's barrel re-exports `renderPage`, which imports `react-dom/static`. Going
  // through the barrel here put the whole prerenderer in the client bundle —
  // measured, on the first build this repository ever ran. `check:bundle` now
  // asserts it stays out.
  // `client/axes` before `react/hydrate` on purpose: the switch is delegation on
  // the document and costs nothing to arm, while hydrating the islands waits on a
  // dynamic import per demo. Armed first, the sidebar's control answers a press
  // that lands while the first demo chunk is still in flight.
  // The site's own modules, imported for their side effects and never named
  // again. Written last among the imports rather than lower down in the file,
  // because a lower position would be a lie: ESM evaluates every import before
  // the first statement, so a side-effect import placed under
  // `wireAxisControls(document)` would still run before it. Last among the
  // imports is the strongest ordering this file can honestly offer — the kit's
  // modules are evaluated, its calls have not run, and a site arms whatever it
  // arms before the first island begins to hydrate.
  //
  // Unresolved specifiers are not caught here on purpose. `Bun.build` reads this
  // file, so a script that does not exist is reported by the resolver with its
  // own message, exactly as a missing demo is — and unlike a stylesheet, which is
  // skipped with a warning, a silently absent script is a site that looks right
  // and does nothing.
  const sideEffects = scripts
    .map(
      (id) =>
        `import ${JSON.stringify(id.startsWith(".") ? specifier(dir, join(root, id)) : id)};\n`,
    )
    .join("");

  // Present only when `mdocs dev` wants questions answerable in the page. Named by
  // path and not by package name: the entry may sit under the temp folder, where
  // the name resolves to nothing. The questions are not demos and have no registry
  // entry — their props are per-instance data on the element, not a module — so
  // the UI package finds and mounts its own markers.
  const names = [
    ...(ui === undefined ? [] : ["wireNavDrawer", "wireSearch"]),
    ...(ui !== undefined && asks ? ["hydrateAsks"] : []),
  ];
  const uiImport =
    ui === undefined
      ? ""
      : `import { ${names.join(", ")} } from ${JSON.stringify(specifier(dir, ui))};\n`;
  const drawerCall =
    ui === undefined ? "" : "wireNavDrawer(document);\nwireSearch(document);\n";
  const askCall = ui !== undefined && asks ? "hydrateAsks(document);\n" : "";

  const entry = join(dir, "entry.ts");
  writeFileSync(
    entry,
    `// Generated by \`mdocs build\`. Do not edit.\nimport { wireAxisControls } from "@standarx/mdocs/client/axes";\nimport { wireTabs } from "@standarx/mdocs/client/tabs";\nimport { wireToc } from "@standarx/mdocs/client/toc";\nimport { hydrateIslands } from "@standarx/mdocs/react/hydrate";\nimport { DEMOS } from "./registry";\n${uiImport}${sideEffects}\nwireAxisControls(document);\nwireTabs(document);\nwireToc(document);\n${drawerCall}void hydrateIslands(document, DEMOS);\n${askCall}`,
    "utf8",
  );

  return { dir, registry, entry };
}
